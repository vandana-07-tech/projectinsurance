import fs from "node:fs/promises";
import path from "node:path";
import { nanoid } from "nanoid";
import { config } from "../config.js";
import { writeJsonArtifact } from "../storage/fileStore.js";
import type {
  PostmanCollectionMeta,
  TestFixture,
  TestScenario,
} from "../shared/schemas.js";
import { ValidationError } from "../shared/errors.js";

interface PostmanItem {
  name: string;
  event?: Array<{ listen: string; script: { type: string; exec: string[] } }>;
  request: {
    method: string;
    header: Array<{ key: string; value: string }>;
    body?: { mode: string; raw: string };
    url: {
      raw: string;
      host: string[];
      path: string[];
    };
  };
}

export async function runApiTestAgent(input: {
  projectId: string;
  projectName: string;
  scenarios: TestScenario[];
  fixtures: TestFixture[];
}): Promise<{ meta: PostmanCollectionMeta; collection: unknown }> {
  const approved = input.scenarios.filter((s) => s.status === "approved");
  if (!approved.length) {
    throw new ValidationError("No approved scenarios for collection generation");
  }

  const fixtureByScenario = new Map(input.fixtures.map((f) => [f.scenarioId, f]));
  const items: PostmanItem[] = [];
  const unresolvedAssumptions: string[] = [];

  // Ensure SC-001 (or first accept) runs before duplicate scenario when present
  const ordered = orderScenarios(approved);

  for (const scenario of ordered) {
    const fixture = fixtureByScenario.get(scenario.id);
    if (!fixture) {
      throw new ValidationError(`Missing fixture for scenario ${scenario.id}`);
    }

    const expectedCodes =
      scenario.expectedStatusCodes && scenario.expectedStatusCodes.length
        ? scenario.expectedStatusCodes
        : scenario.expectedOutcome === "accept"
          ? [201]
          : scenario.expectedOutcome === "reject"
            ? [400, 409]
            : [200, 201, 400, 409];

    if (!scenario.expectedStatusCodes?.length) {
      unresolvedAssumptions.push(
        `${scenario.id}: expected HTTP statuses inferred from mock API contract`
      );
    }

    const codesLiteral = JSON.stringify(expectedCodes);
    const expectAccept = scenario.expectedOutcome === "accept";

    items.push({
      name: `${scenario.id} — ${scenario.name}`,
      event: [
        {
          listen: "test",
          script: {
            type: "text/javascript",
            exec: [
              `pm.test("HTTP status matches expected outcome for ${scenario.id}", function () {`,
              `  pm.expect([${expectedCodes.join(", ")}]).to.include(pm.response.code);`,
              `});`,
              `pm.test("Response has status or error shape", function () {`,
              `  const body = pm.response.json();`,
              expectAccept
                ? `  pm.expect(body).to.have.property("status");`
                : `  pm.expect(body).to.have.property("error");`,
              `});`,
              `pm.globals.set("lastScenarioId", "${scenario.id}");`,
              `// expectedCodes=${codesLiteral}`,
            ],
          },
        },
      ],
      request: {
        method: "POST",
        header: [
          { key: "Content-Type", value: "application/json" },
          { key: "X-Scenario-Id", value: scenario.id },
          { key: "X-Business-Rules", value: scenario.businessRuleIds.join(",") },
        ],
        body: {
          mode: "raw",
          raw: JSON.stringify(fixture.requestPayload, null, 2),
        },
        url: {
          raw: "{{baseUrl}}/api/claims",
          host: ["{{baseUrl}}"],
          path: ["api", "claims"],
        },
      },
    });
  }

  const collectionId = `COL-${nanoid(8)}`;
  const collection = {
    info: {
      _postman_id: collectionId,
      name: `${input.projectName} — Life Claim Tests`,
      description:
        "Generated by API Test Agent for life insurance. Synthetic data only. Traceability via X-Scenario-Id headers.",
      schema: "https://schema.getpostman.com/json/collection/v2.1.0/collection.json",
    },
    item: items,
    variable: [{ key: "baseUrl", value: config.mockApiBaseUrl }],
  };

  validateCollectionStructure(collection);

  const relativeCollection = path.join(
    "collections",
    input.projectId,
    `${collectionId}.postman_collection.json`
  );
  const collectionPath = await writeJsonArtifact(relativeCollection, collection);

  const environment = {
    id: `ENV-${nanoid(6)}`,
    name: `${input.projectName} Environment`,
    values: [
      { key: "baseUrl", value: config.mockApiBaseUrl, enabled: true },
    ],
  };
  const relativeEnv = path.join(
    "collections",
    input.projectId,
    `${collectionId}.postman_environment.json`
  );
  const environmentPath = await writeJsonArtifact(relativeEnv, environment);

  const meta: PostmanCollectionMeta = {
    id: collectionId,
    name: collection.info.name,
    requestCount: items.length,
    scenarioIds: ordered.map((s) => s.id),
    createdAt: new Date().toISOString(),
    collectionPath,
    environmentPath,
    unresolvedAssumptions: [...new Set(unresolvedAssumptions)],
  };

  // Keep a copy under artifacts for export convenience
  await fs.mkdir(path.join(config.artifactsDir, input.projectId), { recursive: true });
  await fs.copyFile(
    collectionPath,
    path.join(config.artifactsDir, input.projectId, `${collectionId}.json`)
  );

  return { meta, collection };
}

function orderScenarios(scenarios: TestScenario[]): TestScenario[] {
  const list = [...scenarios];
  list.sort((a, b) => {
    const aDup = a.category === "duplicate" ? 1 : 0;
    const bDup = b.category === "duplicate" ? 1 : 0;
    if (aDup !== bDup) return aDup - bDup;
    return a.id.localeCompare(b.id);
  });
  return list;
}

function validateCollectionStructure(collection: {
  info?: { schema?: string; name?: string };
  item?: unknown[];
}): void {
  if (!collection.info?.name) {
    throw new ValidationError("Generated collection missing info.name");
  }
  if (!collection.info.schema?.includes("collection/v2.1.0")) {
    throw new ValidationError("Generated collection must use Postman Collection v2.1 schema");
  }
  if (!Array.isArray(collection.item) || collection.item.length === 0) {
    throw new ValidationError("Generated collection has no requests");
  }
}
